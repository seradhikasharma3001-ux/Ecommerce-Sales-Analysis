
/*
====================================================
PROJECT NAME: E-COMMERCE SALES ANALYSIS
DATABASE: Ecommerce_Portfolio
TOOL: Microsoft SQL Server (SSMS)
PROJECT TYPE: Data Analytics - SQL Portfolio

OBJECTIVE:
Analyze e-commerce sales, customers, products,
orders, payments and business performance.

TABLES USED:
1. Customers
2. Products
3. Orders
4. OrderDetails
5. Payments
*/

/*==================================================


SECTION 1: ORDER STATUS ANALYSIS

BUSINESS OBJECTIVE:
To analyze orders based on their status
and calculate the total number of orders
and total order value for each status.

BUSINESS PURPOSE:
To evaluate order performance, monitor
pending and cancelled orders, and understand
sales distribution across different statuses.
=============================================*/
SELECT
    OrderStatus,
    COUNT(OrderID) AS TotalOrders,
    SUM(TotalAmount) AS TotalOrderValue
FROM Orders
GROUP BY OrderStatus;
/* =====================================
   
SECTION 2: DELIVERED REVENUE ANALYSIS

BUSINESS OBJECTIVE:
To identify the total number of successfully
delivered orders and calculate the total revenue
generated from delivered orders.

BUSINESS PURPOSE:
To evaluate completed sales performance and
measure revenue generated from successful
order deliveries.
======================================= */
SELECT
    COUNT(OrderID) AS DeliveredOrders,
    SUM(TotalAmount) AS DeliveredRevenue
FROM Orders
WHERE OrderStatus = 'Delivered';

/*
SECTION 3: PAYMENT STATUS ANALYSIS

BUSINESS OBJECTIVE:
To analyze the number and total amount of payments
across each payment status, including Successful,
Pending, and Failed payments.

BUSINESS PURPOSE:
To monitor payment performance and identify
pending or unsuccessful payment amounts.
*/

SELECT
    PaymentStatus,
    COUNT(PaymentID) AS TotalPayments,
    SUM(PaymentAmount) AS TotalPaymentAmount
FROM Payments
GROUP BY PaymentStatus;

/*
SECTION 4: PAYMENT METHOD ANALYSIS

BUSINESS OBJECTIVE:
To analyze the number of payments and total
payment amount for each payment method.

BUSINESS PURPOSE:
To identify popular payment methods and
understand customer payment preferences.
*/

SELECT
    PaymentMethod,
    COUNT(PaymentID) AS TotalPayments,
    SUM(PaymentAmount) AS TotalPaymentAmount
FROM Payments
GROUP BY PaymentMethod;

/*
SECTION 5: CITY-WISE SALES ANALYSIS

BUSINESS OBJECTIVE:
To analyze the total number of orders and
total sales value generated from each city.

BUSINESS PURPOSE:
To identify high-performing cities,
understand geographical sales distribution,
and identify potential markets for expansion.
*/

SELECT
    C.City,
    COUNT(O.OrderID) AS TotalOrders,
    SUM(O.TotalAmount) AS TotalSales
FROM Customers AS C
INNER JOIN Orders AS O
    ON C.CustomerID = O.CustomerID
GROUP BY C.City
ORDER BY TotalSales DESC;

/*
SECTION 6: PRODUCT-WISE SALES ANALYSIS

BUSINESS OBJECTIVE:
To calculate the total quantity sold and
total sales value generated by each product.

BUSINESS PURPOSE:
To identify best-selling products, understand
product demand, and evaluate product performance.
*/

SELECT
    P.ProductName,
    SUM(OD.Quantity) AS TotalQuantitySold,
    SUM(OD.Quantity * OD.UnitPrice) AS TotalSales
FROM Products AS P
INNER JOIN OrderDetails AS OD
    ON P.ProductID = OD.ProductID
GROUP BY P.ProductName
ORDER BY TotalSales DESC;

/*
SECTION 7: NET SALES AFTER DISCOUNT

BUSINESS OBJECTIVE:
To calculate product-wise net sales after
deducting discounts from the gross sales value.

BUSINESS PURPOSE:
To understand the impact of discounts on revenue
and evaluate actual sales value after discounts.
*/

SELECT
    P.ProductName,
    SUM(OD.Quantity * OD.UnitPrice) AS GrossSales,
    SUM(
        OD.Quantity * OD.UnitPrice * (1 - OD.Discount)
    ) AS NetSales
FROM Products AS P
INNER JOIN OrderDetails AS OD
    ON P.ProductID = OD.ProductID
GROUP BY P.ProductName
ORDER BY NetSales DESC;

/*
SECTION 8: CATEGORY-WISE SALES ANALYSIS

BUSINESS OBJECTIVE:
To calculate the total quantity sold and net
sales revenue generated by each product category
after applying discounts.

BUSINESS PURPOSE:
To identify high-performing product categories,
understand customer demand, and support
inventory and marketing decisions.
*/

SELECT
    P.Category,
    SUM(OD.Quantity) AS TotalQuantitySold,
    SUM(
        OD.Quantity * OD.UnitPrice * (1 - OD.Discount)
    ) AS NetSales
FROM Products AS P
INNER JOIN OrderDetails AS OD
    ON P.ProductID = OD.ProductID
GROUP BY P.Category
ORDER BY NetSales DESC;

/*
SECTION 9: TOP 5 CUSTOMERS BY SALES

BUSINESS OBJECTIVE:
To identify the top 5 customers who have
generated the highest total sales value.

BUSINESS PURPOSE:
To identify high-value customers and support
customer retention and loyalty strategies.
*/

SELECT TOP 5
    C.CustomerID,
    C.CustomerName,
    SUM(O.TotalAmount) AS TotalSales
FROM Customers AS C
INNER JOIN Orders AS O
    ON C.CustomerID = O.CustomerID
GROUP BY
    C.CustomerID,
    C.CustomerName
ORDER BY TotalSales DESC;

/*
SECTION 10: MONTHLY SALES ANALYSIS

BUSINESS OBJECTIVE:
To calculate the total number of orders and
total sales value generated in each month.

BUSINESS PURPOSE:
To identify monthly sales trends, understand
business performance, and support future
sales planning and forecasting.
*/

SELECT
    YEAR(OrderDate) AS SalesYear,
    MONTH(OrderDate) AS SalesMonth,
    COUNT(OrderID) AS TotalOrders,
    SUM(TotalAmount) AS MonthlySales
FROM Orders
GROUP BY
    YEAR(OrderDate),
    MONTH(OrderDate)
ORDER BY
    SalesYear,
    SalesMonth;

/*
SECTION 11: ORDER VS PAYMENT RECONCILIATION

BUSINESS OBJECTIVE:
To compare order amounts with payment amounts
for each order and identify any differences.

BUSINESS PURPOSE:
To verify financial consistency, identify
payment discrepancies, and improve
financial reporting accuracy.
*/

SELECT
    O.OrderID,
    O.TotalAmount AS OrderAmount,
    P.PaymentAmount,
    O.TotalAmount - P.PaymentAmount AS AmountDifference
FROM Orders AS O
INNER JOIN Payments AS P
    ON O.OrderID = P.OrderID
ORDER BY O.OrderID;

/*
SECTION 12: PAYMENT MISMATCH IDENTIFICATION

BUSINESS OBJECTIVE:
To compare order amounts with payment amounts
and classify each transaction as Matched
or Mismatched.

BUSINESS PURPOSE:
To identify financial discrepancies and
support accurate payment reconciliation.
*/

SELECT
    O.OrderID,
    O.TotalAmount AS OrderAmount,
    P.PaymentAmount,
    CASE
        WHEN O.TotalAmount = P.PaymentAmount
            THEN 'Matched'
        ELSE 'Mismatched'
    END AS ReconciliationStatus
FROM Orders AS O
INNER JOIN Payments AS P
    ON O.OrderID = P.OrderID;

/*
SECTION 13: PAYMENT SUCCESS RATE ANALYSIS

BUSINESS OBJECTIVE:
To calculate the percentage of successful
payments out of total payment transactions.

BUSINESS PURPOSE:
To evaluate payment performance and identify
opportunities to improve transaction success.
*/

SELECT
    COUNT(PaymentID) AS TotalPayments,

    SUM(
        CASE
            WHEN PaymentStatus = 'Successful'
            THEN 1
            ELSE 0
        END
    ) AS SuccessfulPayments,

    CAST(
        SUM(
            CASE
                WHEN PaymentStatus = 'Successful'
                THEN 1
                ELSE 0
            END
        ) * 100.0 / COUNT(PaymentID)
        AS DECIMAL(10,2)
    ) AS PaymentSuccessRate
FROM Payments;

/*
SECTION 14: FAILED PAYMENT ANALYSIS

BUSINESS OBJECTIVE:
To identify failed payment transactions and
calculate their total count and payment amount
for each payment method.

BUSINESS PURPOSE:
To identify payment failure patterns and help
improve payment processing performance.
*/

SELECT
    PaymentMethod,
    COUNT(PaymentID) AS FailedPayments,
    SUM(PaymentAmount) AS FailedPaymentAmount
FROM Payments
WHERE PaymentStatus = 'Failed'
GROUP BY PaymentMethod
ORDER BY FailedPaymentAmount DESC;

/*
SECTION 15: REPEAT CUSTOMER ANALYSIS

BUSINESS OBJECTIVE:
To identify customers who have placed more
than one order and calculate their total
orders and total spending.

BUSINESS PURPOSE:
To measure customer retention, identify
repeat buyers, and understand customer loyalty.
*/

SELECT
    C.CustomerID,
    C.CustomerName,
    COUNT(O.OrderID) AS TotalOrders,
    SUM(O.TotalAmount) AS TotalSpending
FROM Customers AS C
INNER JOIN Orders AS O
    ON C.CustomerID = O.CustomerID
GROUP BY
    C.CustomerID,
    C.CustomerName
HAVING COUNT(O.OrderID) > 1
ORDER BY TotalSpending DESC;

/*
SECTION 15: REPEAT CUSTOMER ANALYSIS

BUSINESS OBJECTIVE:
To identify customers who have placed more
than one order and calculate their total
orders and total spending.

BUSINESS PURPOSE:
To measure customer retention, identify
repeat buyers, and understand customer loyalty.
*/

SELECT
    C.CustomerID,
    C.CustomerName,
    COUNT(O.OrderID) AS TotalOrders,
    SUM(O.TotalAmount) AS TotalSpending
FROM Customers AS C
INNER JOIN Orders AS O
    ON C.CustomerID = O.CustomerID
GROUP BY
    C.CustomerID,
    C.CustomerName
HAVING COUNT(O.OrderID) > 1
ORDER BY TotalSpending DESC;

/*
SECTION 16: AVERAGE ORDER VALUE (AOV) ANALYSIS

BUSINESS OBJECTIVE:
To calculate the average amount spent
per order by customers.

BUSINESS PURPOSE:
To measure average customer spending
and evaluate overall order value performance.
*/

SELECT
    COUNT(OrderID) AS TotalOrders,
    SUM(TotalAmount) AS TotalRevenue,
    AVG(TotalAmount) AS AverageOrderValue
FROM Orders;

/*
SECTION 17: CUSTOMER-WISE AVERAGE SPENDING

BUSINESS OBJECTIVE:
To calculate the average order value and
total spending for each customer.

BUSINESS PURPOSE:
To understand customer spending behaviour,
identify high-value customers, and support
personalized marketing strategies.
*/

SELECT
    C.CustomerID,
    C.CustomerName,
    COUNT(O.OrderID) AS TotalOrders,
    AVG(O.TotalAmount) AS AverageSpending,
    SUM(O.TotalAmount) AS TotalSpending
FROM Customers AS C
INNER JOIN Orders AS O
    ON C.CustomerID = O.CustomerID
GROUP BY
    C.CustomerID,
    C.CustomerName
ORDER BY TotalSpending DESC;

/*
SECTION 18: TOP 5 PRODUCTS BY REVENUE

BUSINESS OBJECTIVE:
To identify the top 5 products generating
the highest net sales revenue after discounts.

BUSINESS PURPOSE:
To identify high-revenue products, evaluate
product performance, and support inventory
and sales strategies.
*/

SELECT TOP 5
    P.ProductID,
    P.ProductName,
    SUM(OD.Quantity) AS TotalQuantitySold,
    SUM(
        OD.Quantity * OD.UnitPrice * (1 - OD.Discount)
    ) AS NetRevenue
FROM Products AS P
INNER JOIN OrderDetails AS OD
    ON P.ProductID = OD.ProductID
GROUP BY
    P.ProductID,
    P.ProductName
ORDER BY NetRevenue DESC;

/*
SECTION 19: STOCK AVAILABILITY ANALYSIS

BUSINESS OBJECTIVE:
To classify products based on available stock
quantity into Low, Medium, and Healthy Stock.

BUSINESS PURPOSE:
To monitor inventory levels, identify products
requiring restocking, and prevent stock shortages.
*/

SELECT
    ProductID,
    ProductName,
    StockQuantity,
    CASE
        WHEN StockQuantity <= 15 THEN 'Low Stock'
        WHEN StockQuantity <= 30 THEN 'Medium Stock'
        ELSE 'Healthy Stock'
    END AS StockStatus
FROM Products
ORDER BY StockQuantity ASC;

/*
SECTION 20: CATEGORY-WISE PRODUCT RANKING

BUSINESS OBJECTIVE:
To rank products within each category based
on their net sales revenue after discounts.

BUSINESS PURPOSE:
To identify top-performing products in each
category and support inventory and sales decisions.
*/

WITH ProductSales AS
(
    SELECT
        P.Category,
        P.ProductName,
        SUM(
            OD.Quantity * OD.UnitPrice * (1 - OD.Discount)
        ) AS NetRevenue
    FROM Products AS P
    INNER JOIN OrderDetails AS OD
        ON P.ProductID = OD.ProductID
    GROUP BY
        P.Category,
        P.ProductName
)

SELECT
    Category,
    ProductName,
    NetRevenue,
    RANK() OVER
    (
        PARTITION BY Category
        ORDER BY NetRevenue DESC
    ) AS ProductRank
FROM ProductSales
ORDER BY
    Category,
    ProductRank;

/*
SECTION 21: RUNNING TOTAL OF SALES

BUSINESS OBJECTIVE:
To calculate cumulative sales revenue by
adding each month's sales to all previous months.

BUSINESS PURPOSE:
To monitor cumulative business performance,
track revenue growth, and support financial planning.
*/

WITH MonthlySales AS
(
    SELECT
        YEAR(OrderDate) AS SalesYear,
        MONTH(OrderDate) AS SalesMonth,
        SUM(TotalAmount) AS MonthlyRevenue
    FROM Orders
    GROUP BY
        YEAR(OrderDate),
        MONTH(OrderDate)
)

SELECT
    SalesYear,
    SalesMonth,
    MonthlyRevenue,
    SUM(MonthlyRevenue) OVER
    (
        ORDER BY SalesYear, SalesMonth
        ROWS BETWEEN UNBOUNDED PRECEDING
        AND CURRENT ROW
    ) AS RunningTotal
FROM MonthlySales
ORDER BY SalesYear, SalesMonth;

/*
SECTION 22: MONTH-OVER-MONTH SALES GROWTH

BUSINESS OBJECTIVE:
To calculate the percentage increase or
decrease in monthly sales compared with
the previous month.

BUSINESS PURPOSE:
To identify monthly sales trends, evaluate
business growth, and support decision-making.
*/

WITH MonthlySales AS
(
    SELECT
        YEAR(OrderDate) AS SalesYear,
        MONTH(OrderDate) AS SalesMonth,
        SUM(TotalAmount) AS MonthlyRevenue
    FROM Orders
    GROUP BY
        YEAR(OrderDate),
        MONTH(OrderDate)
),

PreviousMonthSales AS
(
    SELECT
        SalesYear,
        SalesMonth,
        MonthlyRevenue,
        LAG(MonthlyRevenue) OVER
        (
            ORDER BY SalesYear, SalesMonth
        ) AS PreviousMonthRevenue
    FROM MonthlySales
)

SELECT
    SalesYear,
    SalesMonth,
    MonthlyRevenue,
    PreviousMonthRevenue,
    CAST(
        (MonthlyRevenue - PreviousMonthRevenue)
        * 100.0 / NULLIF(PreviousMonthRevenue, 0)
        AS DECIMAL(10,2)
    ) AS MoMGrowthPercentage
FROM PreviousMonthSales
ORDER BY SalesYear, SalesMonth;

/*
SECTION 23: CUSTOMER SEGMENTATION ANALYSIS

BUSINESS OBJECTIVE:
To classify customers into High, Medium, and
Low spending segments based on their total
order value.

BUSINESS PURPOSE:
To understand customer spending behaviour,
identify valuable customers, and support
targeted marketing strategies.
*/

WITH CustomerSpending AS
(
    SELECT
        C.CustomerID,
        C.CustomerName,
        SUM(O.TotalAmount) AS TotalSpending
    FROM Customers AS C
    INNER JOIN Orders AS O
        ON C.CustomerID = O.CustomerID
    GROUP BY
        C.CustomerID,
        C.CustomerName
)

SELECT
    CustomerID,
    CustomerName,
    TotalSpending,
    CASE
        WHEN TotalSpending >= 50000 THEN 'High Value'
        WHEN TotalSpending >= 20000 THEN 'Medium Value'
        ELSE 'Low Value'
    END AS CustomerSegment
FROM CustomerSpending
ORDER BY TotalSpending DESC;

/*
SECTION 24: CUSTOMER LIFETIME VALUE (CLV) ANALYSIS

BUSINESS OBJECTIVE:
To calculate the total historical order value
generated by each customer.

BUSINESS PURPOSE:
To understand customer revenue contribution,
identify valuable customers, and support
long-term customer retention strategies.
*/

SELECT
    C.CustomerID,
    C.CustomerName,
    COUNT(O.OrderID) AS TotalOrders,
    SUM(O.TotalAmount) AS CustomerLifetimeValue
FROM Customers AS C
INNER JOIN Orders AS O
    ON C.CustomerID = O.CustomerID
GROUP BY
    C.CustomerID,
    C.CustomerName
ORDER BY CustomerLifetimeValue DESC;

/*
SECTION 25: FINAL BUSINESS KPI REPORT

BUSINESS OBJECTIVE:
To generate a consolidated business report
using key performance indicators such as total
orders, total order value, delivered orders,
pending orders, cancelled orders, and AOV.

BUSINESS PURPOSE:
To evaluate overall business performance,
monitor order status distribution, and
support management decision-making.
*/

SELECT
    COUNT(OrderID) AS TotalOrders,

    SUM(TotalAmount) AS TotalOrderValue,

    SUM(
        CASE
            WHEN OrderStatus = 'Delivered'
            THEN 1 ELSE 0
        END
    ) AS DeliveredOrders,

    SUM(
        CASE
            WHEN OrderStatus = 'Pending'
            THEN 1 ELSE 0
        END
    ) AS PendingOrders,

    SUM(
        CASE
            WHEN OrderStatus = 'Cancelled'
            THEN 1 ELSE 0
        END
    ) AS CancelledOrders,

    AVG(TotalAmount) AS AverageOrderValue

FROM Orders;

